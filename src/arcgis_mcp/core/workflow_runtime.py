"""Standalone workflow worker and small step SDK; Python 3.9, stdlib + ArcPy only.

Scripts are trusted local code, NOT sandboxed. Only declared SDK steps are traced.
Run with a request manifest generated by the service/CLI, not arbitrary RPC.
"""
import contextlib
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import threading
import time
import traceback

if __name__ == '__main__':
    sys.path.insert(0, str(Path(__file__).resolve().parent))

from history import History, canonical, process_alive
from ops import safety
from ops.common import WorkerError, ensure_output_container, path_exists

# Reading computed environments such as scratchGDB can itself create a GDB.
ENVIRONMENT_KEYS = ('workspace', 'scratchWorkspace', 'outputCoordinateSystem', 'extent',
    'snapRaster', 'cellSize', 'XYTolerance', 'XYResolution', 'ZTolerance', 'MTolerance',
    'parallelProcessingFactor', 'randomGenerator', 'preserveGlobalIds', 'overwriteOutput')


class AuditStream:
    def __init__(self, workflow, name, stream):
        self.workflow, self.name, self.stream = workflow, name, stream

    def write(self, value):
        if value:
            for start in range(0, len(value), 4000):
                self.workflow.event(self.name, {'text': value[start:start + 4000]})
            self.stream.write(value)
            self.stream.flush()
        return len(value)

    def flush(self):
        self.stream.flush()


class Workflow:
    def __init__(self, request):
        self.request = request
        self.root = Path(request['root']).resolve()
        self.job_id = request['job_id']
        self.history = History(self.root)
        self.output_gdb = str(Path(request['output_gdb']).resolve())
        self.mode = request.get('mode', 'final')
        self.input_mode = request.get('input_mode', 'snapshot')
        if self.input_mode not in ('snapshot', 'read_only'):
            raise WorkerError('input_mode 必须为 snapshot/read_only。')
        self.layout = request.get('layout') or {'process': self.output_gdb,
            'temporary': str(self.root / 'temporary.gdb'), 'delivery': str(self.root / 'delivery.gdb')}
        self.parameters = request.get('parameters') or {}
        self.inputs = {}
        self.known = set()
        self.steps = []
        self.final_outputs = {}
        self.active = None
        self.failed = False
        self.environment = {}
        self.native_scratch = self.root / '.arcgis-mcp' / 'scratch' / 'workflow_native'
        self.validations = []
        self.analysis_only = False
        try:
            Path(self.output_gdb).relative_to(self.root)
        except ValueError:
            raise WorkerError('工作流输出库必须位于项目内。')
        if Path(self.output_gdb).suffix.lower() != '.gdb':
            raise WorkerError('output_gdb 必须是 File GDB 路径。')

    def event(self, stage, details):
        try:
            self.history.event(self.job_id, stage, details)
        except Exception:
            self.failed = True
            raise

    def step(self, name, inputs, parameters=None, reason=None, allow_no_output=False):
        if allow_no_output and self.mode != 'draft':
            raise WorkerError('无输出步骤仅用于 draft 分析。')
        return Step(self, name, inputs, parameters, reason=reason, allow_no_output=allow_no_output)

    def finish_analysis(self):
        if self.mode != 'draft':
            raise WorkerError('只有 draft 可以声明无输出分析。')
        self.analysis_only = True

    def workspace_for(self, role=None):
        role = role or ('temporary' if self.mode == 'draft' else 'process')
        if role not in ('process', 'temporary', 'delivery') or (self.mode == 'draft' and role != 'temporary'):
            raise WorkerError('实验步骤只能使用临时区；输出角色必须是 process/temporary/delivery。')
        if self.mode == 'final' and role == 'temporary':
            raise WorkerError('正式步骤不能把已登记输出写入临时区。')
        target = self.layout[role]
        with safety.WorkspaceLease(os.path.join(target, '_lease_target')):
            ensure_output_container(os.path.join(target, '_container_check'))
        return target

    def data_role(self, path):
        path = Path(path).resolve()
        try:
            path.relative_to(self.root / '.arcgis-mcp')
            return 'temporary'
        except ValueError:
            pass
        for role in ('temporary', 'delivery', 'process'):
            for base in (Path(self.layout[role]), self.root / (role + '_files')):
                try:
                    path.relative_to(base)
                    return role
                except ValueError:
                    pass
        return 'original'

    def prepare(self):
        import arcpy
        safety.CURRENT_ROOT = str(self.root)
        safety.CURRENT_JOB = self.job_id
        safety.AUTO_CREATE_GDB = self.request.get('auto_create_gdb', True)
        safety.OUTPUT_WORKSPACE = self.output_gdb
        safety.DEFER_LEASE_RELEASE = True
        arcpy.ResetEnvironments()
        self.native_scratch.parent.mkdir(parents=True, exist_ok=True)
        with safety.WorkspaceLease(str(self.native_scratch / 'scratch.gdb')):
            marker = self.native_scratch / '.mcp-scratch.json'
            if self.native_scratch.exists():
                if self.native_scratch.is_symlink() or not marker.is_file() or json.loads(
                        marker.read_text(encoding='utf-8')).get('kind') != 'workflow_native_v1':
                    raise WorkerError('原生临时目录缺少所有权标记，拒绝接管。')
            else:
                self.native_scratch.mkdir()
                marker.write_text(json.dumps({'kind': 'workflow_native_v1', 'root': str(self.root)}), encoding='utf-8')
        arcpy.env.scratchWorkspace = str(self.native_scratch)
        self.environment = {'pid': os.getpid(), 'python': sys.version, 'arcgis': arcpy.GetInstallInfo(),
            'initial_environments': {key: str(getattr(arcpy.env, key, None)) for key in (
                'outputCoordinateSystem', 'extent', 'snapRaster', 'cellSize', 'XYTolerance',
                'parallelProcessingFactor', 'randomGenerator')}}
        self.event('workflow_environment', self.environment)
        with safety.WorkspaceLease(os.path.join(self.output_gdb, '_lease_target')):
            ensure_output_container(os.path.join(self.output_gdb, '_container_check'))
        aliases = self.request.get('inputs') or {}
        for alias, source in aliases.items():
            if not isinstance(alias, str) or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', alias):
                raise WorkerError('输入别名须为 Python 标识符：' + str(alias))
            if self.input_mode == 'read_only':
                if not path_exists(source):
                    raise WorkerError('只读引用输入不存在：' + source)
                self.event('input_reference', {'alias': alias, 'source': source, 'access': 'read_only',
                    'enforced_by_runtime': False, 'note': '需要部署只读权限，代码不得写入。'})
                self.inputs[alias] = source
                self.known.add(canonical(source))
                continue
            step = Step(self, 'snapshot_' + alias, [source], {}, snapshot=True)
            with step:
                step.edit_copy(source)
            self.inputs[alias] = step.result

    def set_outputs(self, outputs):
        if not isinstance(outputs, dict) or not outputs:
            raise WorkerError('set_outputs 必须提供名称到成功成果路径的非空对象。')
        if any(canonical(p) not in self.known for p in outputs.values()):
            raise WorkerError('最终成果必须来自已成功登记的步骤。')
        self.final_outputs = dict(outputs)

    def finish(self):
        if self.active or self.failed:
            raise WorkerError('工作流有未完成或失败步骤，不能报告成功。')
        if not self.final_outputs and not self.analysis_only:
            raise WorkerError('脚本必须调用 workflow.set_outputs 指定最终成果。')
        if any(not path_exists(p) for p in self.final_outputs.values()):
            raise WorkerError('登记的最终成果已不存在。')
        return {'steps': self.steps, 'outputs': [dict(name=k, path=v, exists=True, role=self.data_role(v))
            for k, v in self.final_outputs.items()], 'environment': self.environment,
            'retained_inputs': True, 'mode': self.mode, 'input_mode': self.input_mode, 'validations': self.validations,
            'data_layout': self.layout, 'input_bindings': {alias: {
                'source': self.request['inputs'][alias], 'source_role': self.data_role(self.request['inputs'][alias]),
                'bound_path': path, 'access': self.input_mode,
                'snapshot': path if self.input_mode == 'snapshot' else None,
                'snapshot_role': self.data_role(path) if self.input_mode == 'snapshot' else None}
                for alias, path in self.inputs.items()},
            'source_protection': ('SDK 输入是保留副本；未登记代码行为不受隔离，也未验证。'
                if self.input_mode == 'snapshot' else '只读引用约定；运行器未强制隔离原件，需配置执行账户只读权限。')}


class Step:
    def __init__(self, workflow, name, inputs, parameters=None, snapshot=False, reason=None, allow_no_output=False):
        self.workflow = workflow
        self.name = str(name).strip()
        self.inputs = list(inputs)
        self.parameters = parameters or {}
        self.snapshot = snapshot
        self.reason = reason or workflow.request['reason']
        self.checks = []
        self.allow_no_output = allow_no_output
        self.publications = []
        self.outputs = []
        self.result = None
        self.job_id = None
        self.publishing = False

    def __enter__(self):
        wf = self.workflow
        if wf.failed or wf.active or not self.name:
            raise WorkerError('步骤名不能为空，不允许嵌套或在失败后继续执行。')
        if not self.snapshot and any(canonical(p) not in wf.known for p in self.inputs):
            raise WorkerError('步骤输入只能使用 workflow.inputs 或前一步成功成果。')
        args = {'operation': self.name, 'inputs': self.inputs, 'params': self.parameters,
            'parent_job_id': wf.job_id, 'reason': self.reason,
            'mode': wf.mode, 'workflow_id': wf.request.get('workflow_id'),
            'script_sha256': wf.request['script_sha256']}
        self.job_id = wf.history.create('workflow_step', args, wf.job_id,
            queue_timeout=wf.request.get('timeout_seconds', 3600))
        try:
            wf.history.update(self.job_id, 'running')
            wf.steps.append(self.job_id)
            wf.event('step_started', {'job_id': self.job_id, **args})
            self._record_graph_node()
        except BaseException as exc:
            self._fail(exc)
            raise
        wf.active = self
        safety.CURRENT_JOB = self.job_id
        return self

    def _record_graph_node(self):
        wf = self.workflow
        graph = wf.request.get('graph')
        if graph and not self.snapshot:
            from workflow_plan import WorkflowPlan
            from history import encode
            definition = next(n for n in graph['nodes'] if n['step_id'] == self.name)
            reverse = {canonical(path): wf.request['inputs'][alias] for alias, path in wf.inputs.items()}
            spec = {**definition, 'input_references': definition['inputs'],
                'parameters': self.parameters,
                'inputs': {alias: reverse.get(canonical(path), path)
                           for alias, path in zip(definition['inputs'], self.inputs)},
                'parent_job_id': wf.job_id, 'input_mode': wf.input_mode,
                'script_sha256': hashlib.sha256(definition['code'].encode('utf-8')).hexdigest()}
            plan = WorkflowPlan(wf.root)
            with plan.history.connect() as db:
                db.execute('INSERT INTO workflow_units VALUES(?,?,?,?,?,?)',
                    (self.job_id, graph['workflow_id'], self.name, 'final', encode(spec), time.time()))
            wf.event('workflow_node_snapshot', {'step_job_id': self.job_id, 'definition': spec})

    def output(self, name=None, role=None, label=None):
        """Return an unpublished ArcPy target. Use result/outputs only after leaving the step."""
        if self.workflow.active is not self:
            raise WorkerError('只能在当前步骤内申请输出。')
        import arcpy
        wf = self.workflow
        workspace = wf.workspace_for(role)
        label = arcpy.ValidateTableName(label or self.name, workspace)
        with safety.WorkspaceLease(os.path.join(workspace, '_lease_target')):
            if name is None:
                final = safety.version_path(os.path.join(workspace, label), 'result', reserved=[p.final for p in self.publications])
            else:
                if not isinstance(name, str) or Path(name).name != name or name != arcpy.ValidateTableName(name, workspace):
                    raise WorkerError('output(name) 只能指定合法 GDB 数据集名，不接受路径。')
                final = os.path.join(workspace, name)
            return self._publication(final).work

    def _publication(self, final):
        if any(canonical(final) == canonical(p.final) for p in self.publications):
            raise WorkerError('步骤输出重名。')
        if any(canonical(final) == canonical(p) for p in self.inputs):
            raise WorkerError('输出不能等于步骤输入。')
        publication = safety.Publication(final, root=str(self.workflow.root))
        self.workflow.event('output_prepared', {'step_job_id': self.job_id,
            'work': publication.work, 'output': final})
        self.publications.append(publication)
        return publication

    def edit_copy(self, source, role=None, label=None):
        if self.workflow.active is not self or source not in self.inputs:
            raise WorkerError('edit_copy 必须在步骤内使用已声明的输入。')
        wf = self.workflow
        workspace = wf.workspace_for(role)
        role = role or ('temporary' if wf.mode == 'draft' else 'process')
        # SHP is a file family; preserve its format rather than silently convert it.
        base = (wf.root / ((role + '_files') if wf.request.get('layout') else 'workflow_files') / Path(source).name
                if str(source).lower().endswith('.shp') else Path(workspace) / Path(source).name)
        if str(source).lower().endswith('.shp'):
            base.parent.mkdir(parents=True, exist_ok=True)
        with contextlib.ExitStack() as locks:
            for ws in sorted({safety.workspace(source), safety.workspace(str(base))}, key=str.lower):
                locks.enter_context(safety.WorkspaceLease(os.path.join(ws, '_lease_target')))
            publication = self._publication(safety.version_path(str(base), label or self.name,
                reserved=[p.final for p in self.publications]))
            wf.event('copy_started', {'step_job_id': self.job_id, 'source': source, 'work': publication.work})
            safety.copy_for_edit(source, publication.work)
            wf.event('copied', {'step_job_id': self.job_id, 'source': source, 'work': publication.work})
        return publication.work

    def check(self, name, passed, details=None, required=True):
        """Caller-defined validation: no built-in business thresholds or acceptance policy."""
        if self.workflow.active is not self or not isinstance(passed, bool):
            raise WorkerError('check 必须在步骤内调用，passed 必须是 bool。')
        check = {'name': str(name), 'passed': passed, 'details': details, 'required': bool(required)}
        self.workflow.event('validation', {'step_job_id': self.job_id, **check})
        self.workflow.history.event(self.job_id, 'validation', check)
        self.checks.append(check)
        self.workflow.validations.append({'step': self.name, **check})
        if required and not passed:
            self.workflow.failed = True
            raise WorkerError('脚本声明的验证未通过：' + str(name))
        return passed

    def _fail(self, exc):
        wf = self.workflow
        wf.failed = True
        state = 'unknown' if self.publishing else 'failed'
        with contextlib.suppress(Exception):
            wf.history.update(self.job_id, state, error=str(exc))
            wf.event('step_failed', {'job_id': self.job_id, 'state': state, 'error': str(exc)})

    def __exit__(self, kind, exc, tb):
        wf = self.workflow
        try:
            if exc is not None:
                self._fail(exc)
                return False
            if wf.failed or (not self.publications and not self.allow_no_output):
                raise WorkerError('步骤审计失败或没有登记输出。')
            if any(not path_exists(p.work) for p in self.publications):
                raise WorkerError('步骤未生成全部声明输出；暂存保留，不发布。')
            import arcpy
            messages = str(arcpy.GetMessages())
            wf.event('step_executed', {'job_id': self.job_id, 'messages': messages,
                'environments': {key: str(getattr(arcpy.env, key, None)) for key in ENVIRONMENT_KEYS}})
            for publication in self.publications:
                self.publishing = True
                wf.event('publishing', {'step_job_id': self.job_id,
                    'work': publication.work, 'output': publication.final})
                self.outputs.append(publication.publish())
                wf.event('published', {'step_job_id': self.job_id, 'output': publication.final})
            payload = {'operation': self.name, 'operation_summary': self.name,
                'params': self.parameters, 'inputs': self.inputs,
                'outputs': [{'path': p, 'exists': True, 'role': wf.data_role(p)} for p in self.outputs],
                'input_roles': {p: wf.data_role(p) for p in self.inputs},
                'parent_job_id': wf.job_id, 'script_sha256': wf.request['script_sha256'],
                'reason': self.reason, 'messages': messages,
                'input_access': wf.input_mode, 'source_mutation_policy': 'forbidden',
                'mode': wf.mode, 'workflow_id': wf.request.get('workflow_id'), 'checks': self.checks}
            graph = wf.request.get('graph')
            if graph and not self.snapshot:
                definition = next(n for n in graph['nodes'] if n['step_id'] == self.name)
                for alias, output in zip(definition['outputs'], payload['outputs']):
                    output['name'] = alias
            wf.history.update(self.job_id, 'succeeded', result=payload, inputs=self.inputs, outputs=self.outputs)
            wf.known.update(canonical(p) for p in self.outputs)
            self.result = self.outputs[0] if len(self.outputs) == 1 else None
            wf.event('step_finished', {'job_id': self.job_id, 'outputs': self.outputs})
        except BaseException as error:
            self._fail(error)
            raise
        finally:
            wf.active = None
            safety.CURRENT_JOB = wf.job_id
        return False


def watchdog(parent, deadline):
    while True:
        if not process_alive(parent) or time.monotonic() >= deadline:
            os._exit(124)
        time.sleep(0.5)


def main(manifest):
    request = json.loads(Path(manifest).read_text(encoding='utf-8'))
    folder = Path(manifest).parent
    # Also stop when the supervising worker disappears; never leave an intentional background writer.
    threading.Thread(target=watchdog, args=(request['parent_pid'],
        time.monotonic() + request['timeout_seconds'] + 5), daemon=True).start()
    wf = Workflow(request)
    outcome = {}
    status = 1
    try:
        script = Path(request['script']).read_text(encoding='utf-8')
        if hashlib.sha256(script.encode('utf-8')).hexdigest() != request['script_sha256']:
            raise WorkerError('提交的脚本快照校验失败。')
        with contextlib.redirect_stdout(AuditStream(wf, 'stdout', sys.stdout)), contextlib.redirect_stderr(
                AuditStream(wf, 'stderr', sys.stderr)):
            wf.prepare()
            import arcpy
            with arcpy.EnvManager(workspace=wf.output_gdb, scratchWorkspace=str(wf.native_scratch), overwriteOutput=False):
                exec(compile(script, request['script'], 'exec'),
                    {'__name__': '__main__', '__file__': request['script'], 'workflow': wf})
            outcome = wf.finish()
            status = 0
    except BaseException as exc:
        outcome = {'error': str(exc), 'type': type(exc).__name__, 'traceback': traceback.format_exc(),
                   'steps': wf.steps}
        with contextlib.suppress(Exception):
            wf.event('script_failed', outcome)
    finally:
        safety.release_leases()
        target = folder / 'outcome.json'
        temporary = target.with_suffix('.tmp')
        temporary.write_text(json.dumps(outcome, ensure_ascii=False), encoding='utf-8')
        os.replace(str(temporary), str(target))
    return status


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1]))
